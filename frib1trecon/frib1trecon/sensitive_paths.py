def _get(url: str) -> requests.Response | None:
    try:
        return http_client.get(url, timeout=TIMEOUT, allow_redirects=False, stream=True)
    except requests.RequestException:
        return None


def _probe(base: str, entry) -> dict | None:
    path, signature, label = entry
    r = _get(base + path)
    if r is None or r.status_code != 200:
        return None
    try:
        body = r.raw.read(MAX_BODY, decode_content=True) if r.raw else b""
    finally:
        r.close()
    text = body.decode("utf-8", errors="ignore")
    if not re.search(signature, text, flags=re.MULTILINE):
        if not (path.endswith(".zip") and body[:4] == b"PK\x03\x04"):
            return None
    return {"path": path, "label": label, "url": base + path,
            "secrets": scan_text_for_secrets(text), "snippet": text[:160].replace("\n", " ")}


def check_sensitive_paths(domain: str) -> list[dict]:
    """Rutas sensibles que responden 200 con la firma esperada, en https o http."""
    for scheme in ("https", "http"):
        base = f"{scheme}://{domain}"
        if _get(base + "/") is not None:
            break
    else:
        return []
    with ThreadPoolExecutor(max_workers=WORKERS) as ex:
        results = list(ex.map(lambda e: _probe(base, e), SENSITIVE_PATHS))
    return [r for r in results if r]
